const fs = require('fs');
const path = require('path');
const file = path.join(__dirname, 'apply-character-skills.js');
let s = fs.readFileSync(file, 'utf8');
s = s.replaceAll('/archer.webp', '/archer.png');
s = s.replaceAll("'archer.webp'", "'archer.png'");
s = s.replace('col*128,y:row*128,w:128,h:128', 'col*362,y:row*362,w:362,h:362');
s = s.replace('c.sprite.scale.set(1.05)', 'c.sprite.scale.set(.38)');
fs.writeFileSync(file, s);
console.log('Archer asset mapping ready');
